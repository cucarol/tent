const messages: Record<Lang, Messages> = { zh, en };

/** ?lang= for one visit, then the stored choice, then the browser's first language. */
function detect(): Lang {
  try {
    const asked = new URLSearchParams(location.search).get("lang");
    if (asked === "zh" || asked === "en") return asked;
    const stored = localStorage.getItem(STORE_KEY);
    if (stored === "zh" || stored === "en") return stored;
  } catch {
    /* no browser storage */
  }
  const first =
    typeof navigator === "undefined" ? "" : (navigator.languages?.[0] ?? navigator.language ?? "");
  return /^zh\b/i.test(first) ? "zh" : "en";
}

let current: Lang = detect();
/** The current messages. Components read it while rendering; the app remounts its views when the language changes. */
export let t: Messages = messages[current];
if (typeof document !== "undefined") document.documentElement.lang = t.code;

export const currentLang = () => current;

export function setLang(next: Lang, remember = true) {
  current = next;
  t = messages[next];
  if (typeof document !== "undefined") document.documentElement.lang = t.code;
  if (remember)
    try {
      localStorage.setItem(STORE_KEY, next);
    } catch {
      /* no browser storage */
    }
}
